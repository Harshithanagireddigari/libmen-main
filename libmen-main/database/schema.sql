-- ============================================================================
-- Library Management System - database schema (MySQL 5.7+ / 8.x)
-- ============================================================================
-- This file creates the STRUCTURE ONLY. It intentionally contains NO dummy
-- data: every table starts empty and is filled through the web application.
--
-- How to install on InfinityFree:
--   Option A: hPanel -> phpMyAdmin -> select your database -> Import this file.
--   Option B: just visit /install.php in your browser - it runs these
--             statements for you automatically (they are all IF NOT EXISTS).
-- ============================================================================

-- Run this inside the database you already created in hPanel, e.g.:
--   USE epizy_00000000_library;

-- ---------------------------------------------------------------------------
-- Staff accounts (login). Starts EMPTY - install.php creates the first admin.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    email         VARCHAR(190)  NOT NULL,
    password_hash VARCHAR(255)  NOT NULL,
    role          ENUM('admin','librarian') NOT NULL DEFAULT 'librarian',
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_users_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Books / titles in the collection.
--   copies            = total physical copies owned
--   available copies  = copies - active loans  (computed in queries, never stored)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS books (
    id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    title      VARCHAR(255) NOT NULL,
    author     VARCHAR(255) NOT NULL,
    isbn       VARCHAR(20)  NULL,
    call_no    VARCHAR(60)  NULL,
    category   VARCHAR(60)  NOT NULL DEFAULT 'Other',
    copies     INT UNSIGNED NOT NULL DEFAULT 1,
    cover      VARCHAR(255) NULL,               -- path under uploads/covers/ (optional)
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_books_isbn (isbn)             -- MySQL allows several NULLs here
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Members / borrowers.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS members (
    id           INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    member_code  VARCHAR(20)  NOT NULL,          -- e.g. LIB-0001 (generated by the app)
    name         VARCHAR(255) NOT NULL,
    email        VARCHAR(190) NOT NULL,
    phone        VARCHAR(30)  NULL,
    membership   ENUM('Student','Faculty','General') NOT NULL DEFAULT 'General',
    member_since DATE         NOT NULL,
    valid_till   DATE         NOT NULL,          -- membership expiry date
    status       ENUM('Active','Suspended') NOT NULL DEFAULT 'Active',
    max_books    INT UNSIGNED NOT NULL DEFAULT 5,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_members_code  (member_code),
    UNIQUE KEY uq_members_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Loans (issue / return records).
--   A row with status='issued' and due_date in the past is "overdue"
--   (computed in queries). fine is calculated when the book is returned.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS loans (
    id          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    book_id     INT UNSIGNED NOT NULL,
    member_id   INT UNSIGNED NOT NULL,
    issue_date  DATE         NOT NULL,
    due_date    DATE         NOT NULL,
    return_date DATE         NULL,
    status      ENUM('issued','returned') NOT NULL DEFAULT 'issued',
    fine        DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    reminded_at TIMESTAMP    NULL,                -- last "send reminder" action
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_loans_book   FOREIGN KEY (book_id)   REFERENCES books   (id) ON DELETE RESTRICT,
    CONSTRAINT fk_loans_member FOREIGN KEY (member_id) REFERENCES members (id) ON DELETE RESTRICT,
    KEY idx_loans_status (status),
    KEY idx_loans_due    (due_date),
    KEY idx_loans_issue  (issue_date),
    KEY idx_loans_member (member_id),
    KEY idx_loans_book   (book_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------------
-- Audit trail: every important action in the app is logged here.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS activity_log (
    id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    action     VARCHAR(60)  NOT NULL,             -- e.g. 'book.added', 'loan.issued'
    details    VARCHAR(500) NULL,
    user_id    INT UNSIGNED NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_log_created (created_at),
    KEY idx_log_action  (action)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
